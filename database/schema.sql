CREATE DATABASE IF NOT EXISTS systrack_db CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE systrack_db;
CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, full_name VARCHAR(120) NOT NULL,
 email VARCHAR(160) NOT NULL UNIQUE, password_hash VARCHAR(255) NOT NULL,
 role ENUM('ADMIN','COORDINATOR','TECHNICIAN','REQUESTER') NOT NULL DEFAULT 'REQUESTER',
 active BOOLEAN NOT NULL DEFAULT TRUE, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS assets (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, asset_code VARCHAR(40) NOT NULL UNIQUE,
 name VARCHAR(120) NOT NULL, category VARCHAR(60) NOT NULL, brand VARCHAR(80), model VARCHAR(80),
 serial_number VARCHAR(100), location VARCHAR(120), assigned_to VARCHAR(120),
 status ENUM('OPERATIVO','MANTENIMIENTO','INACTIVO','BAJA') NOT NULL DEFAULT 'OPERATIVO',
 notes TEXT, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS incidents (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, title VARCHAR(160) NOT NULL, description TEXT NOT NULL,
 category VARCHAR(60) NOT NULL DEFAULT 'OTRO', impact ENUM('BAJO','MEDIO','ALTO') NOT NULL DEFAULT 'MEDIO',
 urgency ENUM('BAJA','MEDIA','ALTA') NOT NULL DEFAULT 'MEDIA',
 priority ENUM('BAJA','MEDIA','ALTA','CRITICA') NOT NULL DEFAULT 'MEDIA',
 asset_id BIGINT UNSIGNED NULL, reported_by BIGINT UNSIGNED NOT NULL, assigned_to BIGINT UNSIGNED NULL,
 status ENUM('REGISTRADO','ASIGNADO','EN_PROCESO','RESUELTO','CERRADO') NOT NULL DEFAULT 'REGISTRADO',
 resolution TEXT, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_incident_asset FOREIGN KEY(asset_id) REFERENCES assets(id) ON DELETE SET NULL,
 CONSTRAINT fk_incident_reporter FOREIGN KEY(reported_by) REFERENCES users(id),
 CONSTRAINT fk_incident_assignee FOREIGN KEY(assigned_to) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS maintenances (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, asset_id BIGINT UNSIGNED NOT NULL,
 type ENUM('PREVENTIVO','CORRECTIVO') NOT NULL, description TEXT NOT NULL,
 scheduled_date DATE NOT NULL, technician_id BIGINT UNSIGNED NOT NULL,
 status ENUM('PENDIENTE','COMPLETADO','CANCELADO') NOT NULL DEFAULT 'PENDIENTE',
 work_performed TEXT, observations TEXT, completed_at DATETIME NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_maintenance_asset FOREIGN KEY(asset_id) REFERENCES assets(id),
 CONSTRAINT fk_maintenance_technician FOREIGN KEY(technician_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS activity_logs (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NULL,
 entity VARCHAR(60) NOT NULL, entity_id BIGINT UNSIGNED NOT NULL, action VARCHAR(60) NOT NULL,
 detail JSON NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_log_user FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB;
